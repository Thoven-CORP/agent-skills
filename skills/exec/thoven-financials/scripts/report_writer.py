"""Render analysis dict into a CFO weekly markdown report."""

from datetime import date


def render_report(analysis: dict, window: tuple[date, date]) -> str:
    """
    Render a weekly CFO report. Sections are conditionally included
    (no filler like 'No anomalies this week').
    """
    since, until = window
    sections = []

    # Frontmatter
    sections.append(
        f"""---
date: {until.isoformat()}
category: Finance
status: Weekly Report
window: {since.isoformat()} to {until.isoformat()}
---
"""
    )

    # Heading
    sections.append(
        f"# CFO Weekly — {since.strftime('%b %-d')}–{until.strftime('%-d, %Y')}\n"
    )

    # Top line
    delta_str = (
        f" ({'+' if analysis['runway_delta'] >= 0 else ''}{analysis['runway_delta']:.1f} from last week)"
        if analysis.get("runway_delta") is not None
        else ""
    )
    sections.append(
        f"""## Top Line

- **This week's burn:** ${analysis['week_burn']:,.2f}
- **Cash on hand:** ${analysis['cash_on_hand']:,.2f}
- **Monthly burn (4-week avg):** ${analysis['monthly_burn']:,.0f}/mo
- **Runway:** {analysis['runway_months']:.1f} months{delta_str}
"""
    )

    # Status flags (if any)
    flags = []
    for o in analysis["overages"]:
        flags.append(f"⚠ **OVERAGE — {o['vendor']}:** ${o['mtd']:.0f} MTD vs ${o['cap']} cap ({o['pct_of_cap']:.0f}%)")
    for a in analysis["anomalies"][:3]:  # cap inline at 3
        if a["type"] == "unknown_vendor":
            flags.append(f"⚠ **ANOMALY — Unknown vendor \"{a['description']}\":** ${a['amount']:.0f} on {a['date']}")
        elif a["type"] == "spike":
            flags.append(f"⚠ **SPIKE — {a['vendor']}:** ${a['amount']:.0f} ({a['amount']/a['baseline']:.1f}x typical)")
        elif a["type"] == "first_paid_charge":
            flags.append(f"⚠ **FIRST PAID CHARGE — {a['vendor']}:** ${a['amount']:.2f}")
    if not flags:
        flags = ["✓ All vendors within cap, no anomalies"]
    sections.append(f"## Status — {len(flags)} Flag{'s' if len(flags) != 1 else ''}\n\n" + "\n".join(flags) + "\n")

    # Per-vendor table
    table_rows = ["| Vendor | Type | MTD | Cap | Status |", "|---|---|---|---|---|"]
    sorted_vendors = sorted(analysis["vendor_table"], key=lambda v: -v["pct"])
    for v in sorted_vendors:
        status = f"⚠ {v['pct']:.0f}% OVER" if v["pct"] > 100 else f"✓ {v['pct']:.0f}%"
        table_rows.append(f"| {v['vendor']} | {v['type']} | ${v['mtd']:.0f} | ${v['cap']} | {status} |")
    sections.append("## Per-Vendor Detail (MTD)\n\n" + "\n".join(table_rows) + "\n")

    # Anomalies section (conditional — omit entirely if empty)
    if analysis["anomalies"]:
        anomaly_lines = []
        for a in analysis["anomalies"]:
            if a["type"] == "unknown_vendor":
                anomaly_lines.append(f"- **NEW VENDOR — {a['description']} (${a['amount']:.0f}, {a['date']})** — not in budget doc. Categorize or cancel?")
            elif a["type"] == "spike":
                anomaly_lines.append(f"- **SPIKE — {a['vendor']} on {a['date']} (${a['amount']:.0f})** — {a['amount']/a['baseline']:.1f}x typical")
            elif a["type"] == "first_paid_charge":
                anomaly_lines.append(f"- **FIRST PAID CHARGE — {a['vendor']} (${a['amount']:.2f})** — free-tier broken, signals scale")
        sections.append("## Anomalies\n\n" + "\n".join(anomaly_lines) + "\n")

    # Free-tier watch
    if analysis.get("free_tier_watch"):
        ftw_lines = [f"- {f['vendor']}: ${f['mtd']:.2f} ({f['status']})" for f in analysis["free_tier_watch"]]
        sections.append("## Free-Tier Watch\n\n" + "\n".join(ftw_lines) + "\n")

    # Footer
    sections.append(
        "\n---\nGenerated by CFO weekly agent. Source: Mercury CLI + CFO/2026-05-13-budget-line-items.md\n"
    )

    return "\n".join(sections)
