#!/usr/bin/env python3
"""Installs the enforcement hooks into Codex's hooks.json, and the deny list as Codex rules.

Codex uses the identical hooks.json shape as Claude Code, in its own file.
Codex runs hooks.json only with `[features] hooks = true` in config.toml, which this sets.
Each hook still needs the user's trust in Codex once; this never writes that trust state.
The deny list becomes forbidden prefix_rule entries in ~/.codex/rules/thoven.rules,
which Codex loads with every other file in that folder at startup
(developers.openai.com/codex/rules).
Dry run by default. Pass --apply to write.
"""
import argparse
import copy
import json
import re
import shlex
import sys
from pathlib import Path

from common import ENFORCEMENT_DIR, backup_once, copy_file, load_denies, needs_copy, read_json, write_json

CODEX_DIR = Path.home() / ".codex"
HOOKS_DIR = CODEX_DIR / "hooks"
HOOKS_JSON = CODEX_DIR / "hooks.json"
RULES = CODEX_DIR / "rules" / "thoven.rules"
CONFIG = CODEX_DIR / "config.toml"

FEATURES_HEADER = re.compile(r"^\[features\][ \t]*(#.*)?$", re.M)
TABLE_HEADER = re.compile(r"^\[", re.M)
HOOKS_KEY = re.compile(r"^hooks[ \t]*=[ \t]*(true|false)\b.*$", re.M)


def enable_hooks_feature(text: str):
    """Returns (new text, what changed), or (None, reason) when the edit is unsafe.

    A text edit, because the standard library reads TOML but cannot write it.
    """
    header = FEATURES_HEADER.search(text)
    if header is None:
        if re.search(r"^features[ \t]*[.=]", text, re.M):
            return None, "features is set outside a [features] table; set hooks = true by hand"
        sep = "" if not text or text.endswith("\n\n") else ("\n" if text.endswith("\n") else "\n\n")
        return text + sep + "[features]\nhooks = true\n", "add [features] hooks = true"
    start = header.end()
    nxt = TABLE_HEADER.search(text, start + 1)
    end = nxt.start() if nxt else len(text)
    key = HOOKS_KEY.search(text, start, end)
    if key is None:
        return text[:start] + "\nhooks = true" + text[start:], "add hooks = true to [features]"
    if key.group(1) == "true":
        return text, None
    return text[:key.start()] + "hooks = true" + text[key.end():], "turn [features] hooks from false to true"


def parses_as_toml(text: str) -> bool:
    try:
        import tomllib
    except ImportError:
        return True
    try:
        return tomllib.loads(text).get("features", {}).get("hooks") is True
    except tomllib.TOMLDecodeError:
        return False

# (script name, event, matcher, timeout, args); --pre stamps the start of each shell call
HOOK_SPECS = [
    ("thoven-guard-bash", "PreToolUse", "Bash", 10, ""),
    ("thoven-track-edits", "PreToolUse", "Bash", 10, " --pre"),
    ("thoven-track-edits", "PostToolUse", "Edit|Write|Bash", 10, ""),
    ("thoven-uncommitted", "Stop", None, 10, ""),
    ("thoven-andres-mode", "SessionStart", "startup|clear|compact", 10, ""),
    ("thoven-ticket-recall", "UserPromptSubmit", None, 6, " --harness codex"),
]


def render_rules(denies: list) -> str:
    lines = ["# Generated by agent-skills/enforcement/install/codex.py from config/deny.json. Do not edit."]
    for d in denies:
        lines.append(
            f"prefix_rule(pattern={json.dumps(d['argv'])}, decision=\"forbidden\", "
            f"justification={json.dumps(d['why'])})"
        )
    return "\n".join(lines) + "\n"


def command_for(script_name: str, args: str = "") -> str:
    return str(HOOKS_DIR / script_name) + args


def hook_already_present(config: dict, event: str, command: str) -> bool:
    for entry in config.get("hooks", {}).get(event, []):
        for h in entry.get("hooks", []):
            if h.get("command") == command:
                return True
    return False


def add_hook(config: dict, event: str, matcher, command: str, timeout: int) -> None:
    config.setdefault("hooks", {}).setdefault(event, [])
    hook_entry = {"command": command, "type": "command", "timeout": timeout}
    block = {"hooks": [hook_entry]}
    if matcher:
        block["matcher"] = matcher
    config["hooks"][event].append(block)


def soften_stop_notifications(config: dict) -> int:
    """Desktop access is optional; notification failures must not block completion."""
    changed = 0
    for entry in config.get("hooks", {}).get("Stop", []):
        for hook in entry.get("hooks", []):
            command = hook.get("command", "")
            try:
                argv = shlex.split(command)
            except ValueError:
                continue
            if (len(argv) == 3 and argv[0] in ("osascript", "/usr/bin/osascript")
                    and argv[1] == "-e" and argv[2].startswith("display notification ")):
                hook["command"] = command + " >/dev/null 2>&1 || :"
                changed += 1
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="write changes; default is dry run")
    args = parser.parse_args()

    original = read_json(HOOKS_JSON, {"hooks": {}})
    config = copy.deepcopy(original)
    notifications_changed = soften_stop_notifications(config)

    plan = []
    for script_name, event, matcher, timeout, extra in HOOK_SPECS:
        command = command_for(script_name, extra)
        src = ENFORCEMENT_DIR / "hooks" / script_name
        copy_needed = needs_copy(src, HOOKS_DIR / script_name)
        settings_needed = not hook_already_present(config, event, command)
        plan.append((script_name, event, matcher, timeout, command, copy_needed, settings_needed))

    rules_text = render_rules(load_denies())
    rules_needed = not RULES.exists() or RULES.read_text() != rules_text

    config_text = CONFIG.read_text() if CONFIG.exists() else ""
    new_config, config_change = enable_hooks_feature(config_text)
    if new_config is not None and config_change and not parses_as_toml(new_config):
        new_config, config_change = None, "the edited config.toml would not parse; set hooks = true by hand"

    print(f"Target hooks.json: {HOOKS_JSON}")
    print(f"Target hooks dir: {HOOKS_DIR}")
    if notifications_changed:
        print(f"- Stop desktop notification: make {notifications_changed} hook(s) nonfatal")
    for script_name, event, matcher, timeout, command, copy_needed, settings_needed in plan:
        print(f"- {script_name}: copy={'yes' if copy_needed else 'no (already matches)'} "
              f"hooks_entry[{event}/{matcher or '-'}]={'add' if settings_needed else 'already present'}")
    print(f"- {RULES}: {'write' if rules_needed else 'already matches'}")
    if new_config is None:
        print(f"- {CONFIG}: left alone, {config_change}")
    else:
        print(f"- {CONFIG}: {config_change or 'hooks feature already on'}")

    if not args.apply:
        print("\nDry run only. Re-run with --apply to write.")
        return

    changed = False
    for script_name, event, matcher, timeout, command, copy_needed, settings_needed in plan:
        if copy_needed:
            copy_file(ENFORCEMENT_DIR / "hooks" / script_name, HOOKS_DIR / script_name, executable=True)
            changed = True
        if settings_needed:
            add_hook(config, event, matcher, command, timeout)
            print(f"Added {event}/{matcher or '-'} entry for {script_name}")

    if config != original or not HOOKS_JSON.exists():
        write_json(HOOKS_JSON, config)
        changed = True
    if rules_needed:
        RULES.parent.mkdir(parents=True, exist_ok=True)
        backup_once(RULES)
        RULES.write_text(rules_text)
        print(f"Wrote {RULES}")
        changed = True
    if new_config is not None and config_change:
        CONFIG.parent.mkdir(parents=True, exist_ok=True)
        backup_once(CONFIG)
        CONFIG.write_text(new_config)
        print(f"Wrote {CONFIG}: {config_change}")
        changed = True
    if not changed:
        print("No changes.")


if __name__ == "__main__":
    sys.exit(main())
